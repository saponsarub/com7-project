def inner(panel, top=PAD_TOP):
    x0, y0, x1, y1 = panel
    return (x0 + PAD_X, y0 + top, x1 - x0 - 2 * PAD_X, y1 - y0 - top - PAD_BOT)


def kpi_cells(n, hero=True, y=KPI_Y, h=KPI_H):
    """เซลล์ KPI — ตัวแรกกว้างกว่าเพื่อนเมื่อ hero=True

    กฎ 5 วินาที: ถ้าปิดจอแล้วถามว่าจำอะไรได้ ต้องเป็นตัวที่เราคิดว่าสำคัญสุด
    จึงต้องมีตัวเด่นตัวเดียว ไม่ใช่ทุกใบเท่ากันหมด
    """
    if not hero:
        w = (CW - (n - 1) * GUT) // n
        return [(CX0 + i * (w + GUT), y, w, h) for i in range(n)]
    hw = 3 * COL + 2 * GUT                              # 236 — เด่นแต่ไม่โบ๋
    rest = (CW - hw - GUT - (n - 2) * GUT) // (n - 1)
    out = [(CX0, y, hw, h)]
    x = CX0 + hw + GUT
    for _ in range(n - 1):
        out.append((x, y, rest, h))
        x += rest + GUT
    return out


